//! Claude Code session transcripts: discovery and JSONL decoding.
//!
//! Claude Code writes one append-only JSONL file per session at
//! `<projects>/<bucket>/<session-id>.jsonl`, where the bucket is the working
//! directory with every non-alphanumeric character replaced by `-`. Records
//! form a tree through `uuid`/`parentUuid`; beside the conversation the file
//! carries titles, attachments, hook output, and editor bookkeeping.
//!
//! Subagent transcripts live next to their session, at
//! `<bucket>/<session-id>/subagents/**/agent-<id>.jsonl`, each with an
//! `agent-<id>.meta.json` naming the agent's task.

use std::borrow::Cow;
use std::collections::{BTreeMap, HashSet};
use std::fs::File;
use std::io::{BufRead, BufReader};
use std::ops::ControlFlow;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result};
use serde::Deserialize;
use serde_json::value::RawValue;
use serde_json::Value;
use walkdir::WalkDir;

use crate::convert::from_iso;
use crate::dedup;
use crate::paths;

/// Where a session's name came from, most authoritative first.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum NameSource {
    /// Set by the user with `/rename`.
    Custom,
    /// Agent name the user gave the session.
    Agent,
    /// Generated by Claude Code.
    Ai,
    /// Summary record written by older Claude Code releases.
    Summary,
}

impl NameSource {
    /// The Pi title source with the same meaning.
    pub fn title_source(self) -> &'static str {
        match self {
            NameSource::Custom | NameSource::Agent => "user",
            NameSource::Ai | NameSource::Summary => "auto",
        }
    }
}

/// A session name and where it came from.
#[derive(Debug, Clone)]
pub struct Name {
    /// The name itself.
    pub text: String,
    /// Record kind that set it.
    pub source: NameSource,
}

/// Collects a transcript's name records. Within a kind the latest record wins;
/// across kinds the most authoritative one does.
#[derive(Debug, Default)]
pub struct Names {
    custom: Option<String>,
    agent: Option<String>,
    ai: Option<String>,
    summary: Option<String>,
}

impl Names {
    /// Field holding the name in a record of `kind`, when `kind` names a session.
    pub fn field(kind: &str) -> Option<&'static str> {
        match kind {
            "custom-title" => Some("customTitle"),
            "agent-name" => Some("agentName"),
            "ai-title" => Some("aiTitle"),
            "summary" => Some("summary"),
            _ => None,
        }
    }

    /// Records the name a record of `kind` carries.
    pub fn observe(&mut self, kind: &str, text: &str) {
        let text = text.trim();
        if text.is_empty() {
            return;
        }
        let slot = match kind {
            "custom-title" => &mut self.custom,
            "agent-name" => &mut self.agent,
            "ai-title" => &mut self.ai,
            "summary" => &mut self.summary,
            _ => return,
        };
        *slot = Some(text.to_string());
    }

    /// The winning name, if any record set one.
    pub fn best(self) -> Option<Name> {
        [
            (self.custom, NameSource::Custom),
            (self.agent, NameSource::Agent),
            (self.ai, NameSource::Ai),
            (self.summary, NameSource::Summary),
        ]
        .into_iter()
        .find_map(|(text, source)| text.map(|text| Name { text, source }))
    }
}

/// Where and when a transcript started: the first working directory and the
/// first timestamp its records carry, in file order.
#[derive(Debug, Default, Clone, PartialEq, Eq)]
pub struct Origin {
    /// First non-empty `cwd`.
    pub cwd: Option<String>,
    /// First parseable `timestamp`, in epoch milliseconds.
    pub started: Option<i64>,
}

impl Origin {
    /// Reads `cwd` and `timestamp` from one record; true once both are known.
    fn observe(&mut self, record: &Value) -> bool {
        if self.cwd.is_none() {
            if let Some(cwd) = record.get("cwd").and_then(Value::as_str).filter(|c| !c.is_empty()) {
                self.cwd = Some(cwd.to_string());
            }
        }
        if self.started.is_none() {
            self.started = record.get("timestamp").and_then(timestamp_ms);
        }
        self.cwd.is_some() && self.started.is_some()
    }

    /// Origin of a fully read transcript.
    pub fn of(records: &[Value]) -> Origin {
        let mut origin = Origin::default();
        for record in records {
            if origin.observe(record) {
                break;
            }
        }
        origin
    }
}

/// A record timestamp in epoch milliseconds; Claude Code writes ISO-8601.
pub fn timestamp_ms(value: &Value) -> Option<i64> {
    match value {
        Value::String(text) => from_iso(text),
        Value::Number(number) => number.as_i64(),
        _ => None,
    }
}

/// Model name Claude Code gives the assistant records it writes itself, such
/// as API errors and "no response requested"; no model produced them.
pub const SYNTHETIC_MODEL: &str = "<synthetic>";

/// Session id of a transcript file: its name without `.jsonl`.
pub fn session_id(path: &Path) -> String {
    path.file_stem()
        .map(|s| s.to_string_lossy().to_string())
        .unwrap_or_default()
}

/// Last-modified time of a file in epoch milliseconds, or 0 when unknown.
pub fn mtime_ms(metadata: &std::fs::Metadata) -> i64 {
    metadata
        .modified()
        .ok()
        .and_then(|t| t.duration_since(std::time::UNIX_EPOCH).ok())
        .map(|d| d.as_millis() as i64)
        .unwrap_or(0)
}

/// True for a conversation record that belongs to a subagent rather than the
/// session whose transcript holds it.
pub fn is_sidechain(record: &Value) -> bool {
    record.get("isSidechain").and_then(Value::as_bool) == Some(true)
}

/// The prompt a `queued_command` attachment carries, when no user record holds it.
///
/// A prompt typed while the model is busy is queued, then injected into the
/// next request as an attachment rather than written as a user record, so for
/// most queued prompts the attachment is the only copy. One that did become a
/// user record names that record in `source_uuid`.
pub fn queued_prompt<'a>(record: &'a Value, uuids: &HashSet<&str>) -> Option<&'a Value> {
    if record.get("type").and_then(Value::as_str) != Some("attachment") {
        return None;
    }
    let attachment = record.get("attachment")?;
    if attachment.get("type").and_then(Value::as_str) != Some("queued_command") {
        return None;
    }
    if attachment
        .get("source_uuid")
        .and_then(Value::as_str)
        .is_some_and(|source| uuids.contains(source))
    {
        return None;
    }
    attachment.get("prompt").filter(|prompt| match prompt {
        Value::String(text) => !text.trim().is_empty(),
        Value::Array(items) => !items.is_empty(),
        _ => false,
    })
}

/// Every record uuid of a transcript, for [`queued_prompt`].
pub fn record_uuids(records: &[Value]) -> HashSet<&str> {
    records
        .iter()
        .filter_map(|r| r.get("uuid").and_then(Value::as_str))
        .collect()
}

/// Calls `visit` with every readable object record, in file order.
///
/// A partially written or corrupt line is skipped rather than failing the
/// file, since Claude Code may be appending to it while it is read.
fn for_each_record(path: &Path, mut visit: impl FnMut(Value) -> ControlFlow<()>) -> Result<()> {
    let file = File::open(path).with_context(|| format!("open {}", path.display()))?;
    let mut reader = BufReader::with_capacity(1 << 20, file);
    let mut line = Vec::new();
    loop {
        line.clear();
        let read = reader
            .read_until(b'\n', &mut line)
            .with_context(|| format!("read {}", path.display()))?;
        if read == 0 {
            return Ok(());
        }
        let Ok(value) = serde_json::from_slice::<Value>(&line) else {
            continue;
        };
        if value.is_object() && visit(value).is_break() {
            return Ok(());
        }
    }
}

/// Reads every record of a transcript.
pub fn read_records(path: &Path) -> Result<Vec<Value>> {
    let mut records = Vec::new();
    for_each_record(path, |value| {
        records.push(value);
        ControlFlow::Continue(())
    })?;
    Ok(records)
}

/// Reads only as far as needed to learn a transcript's [`Origin`].
pub fn read_origin(path: &Path) -> Result<Origin> {
    let mut origin = Origin::default();
    for_each_record(path, |value| {
        if origin.observe(&value) {
            ControlFlow::Break(())
        } else {
            ControlFlow::Continue(())
        }
    })?;
    Ok(origin)
}

/// Subagent transcripts recorded for a session, in path order.
pub fn subagent_files(main: &Path) -> Vec<PathBuf> {
    let dir = main.with_extension("").join("subagents");
    let mut files: Vec<PathBuf> = WalkDir::new(dir)
        .into_iter()
        .filter_map(Result::ok)
        .filter(|entry| entry.file_type().is_file())
        .map(|entry| entry.into_path())
        .filter(|path| {
            let name = path.file_name().map(|n| n.to_string_lossy()).unwrap_or_default();
            name.starts_with("agent-") && name.ends_with(".jsonl")
        })
        .collect();
    files.sort();
    files
}

/// Task description from a subagent's `agent-<id>.meta.json`.
pub fn subagent_description(file: &Path) -> Option<String> {
    let meta = file.with_extension("meta.json");
    let parsed: Value = serde_json::from_slice(&std::fs::read(meta).ok()?).ok()?;
    parsed
        .get("description")
        .and_then(Value::as_str)
        .map(str::trim)
        .filter(|d| !d.is_empty())
        .map(str::to_string)
}

/// Projects Claude Code registered in its settings file, as absolute paths.
pub fn registered_projects() -> Vec<String> {
    let Ok(bytes) = std::fs::read(paths::claude_settings_file()) else {
        return Vec::new();
    };
    let Ok(parsed) = serde_json::from_slice::<Value>(&bytes) else {
        return Vec::new();
    };
    parsed
        .get("projects")
        .and_then(Value::as_object)
        .map(|projects| {
            projects
                .keys()
                .filter(|p| p.starts_with('/'))
                .cloned()
                .collect()
        })
        .unwrap_or_default()
}

/// Best guess at the working directory a bucket encodes, for a transcript
/// that never recorded one. The encoding is lossy, so a project Claude Code
/// registered wins over the naive reading.
pub fn bucket_cwd(bucket: &str, registered: &[String]) -> String {
    registered
        .iter()
        .find(|project| paths::encode_claude_bucket(project) == bucket)
        .cloned()
        .unwrap_or_else(|| bucket.replace('-', "/"))
}

/// A Claude Code session discovered on disk.
#[derive(Debug, Clone)]
pub struct SessionRef {
    /// Session id, the transcript's file name.
    pub id: String,
    /// Transcript file.
    pub path: PathBuf,
    /// Project bucket directory name.
    pub bucket: String,
    /// Working directory the transcript recorded, or the bucket's best reading.
    pub cwd: String,
    /// First record time in epoch milliseconds, or the file's mtime.
    pub started: i64,
    /// Session name, when the transcript records one.
    pub name: Option<Name>,
    /// First prompt the user typed, whitespace collapsed.
    pub first_prompt: String,
    /// Conversation messages: prompts, replies, and tool results.
    pub messages: usize,
    /// Responses a model produced. Zero means the session never got an
    /// answer: only slash commands, or prompts nothing replied to.
    pub replies: usize,
    /// Distinct fingerprints of the human prompts, for duplicate detection.
    pub prompts: Vec<u64>,
    /// Number of subagent transcripts beside the session.
    pub subagents: usize,
    /// Transcript size in bytes.
    pub size: u64,
}

impl SessionRef {
    /// What to call the session: its name, else its first prompt, else its id.
    pub fn label(&self) -> &str {
        match &self.name {
            Some(name) => &name.text,
            None if !self.first_prompt.is_empty() => &self.first_prompt,
            None => &self.id,
        }
    }
}

/// Lists every Claude Code session under `root`, newest first.
pub fn discover(root: &Path) -> Vec<SessionRef> {
    let registered = registered_projects();
    let mut out: Vec<SessionRef> = transcripts(root)
        .into_iter()
        .filter_map(|(path, bucket)| inspect(&path, &bucket, &registered))
        .collect();
    out.sort_by(|a, b| b.started.cmp(&a.started).then_with(|| a.id.cmp(&b.id)));
    out
}

/// Listing metadata of one transcript given by path; its bucket is the
/// directory holding it.
pub fn inspect_path(path: &Path) -> Option<SessionRef> {
    let bucket = path
        .parent()
        .and_then(Path::file_name)
        .map(|n| n.to_string_lossy().to_string())
        .unwrap_or_default();
    inspect(path, &bucket, &registered_projects())
}

/// Counts records by type, with attachments split by their own type.
pub fn histogram(records: &[Value]) -> BTreeMap<String, usize> {
    let mut out = BTreeMap::new();
    for record in records {
        let kind = record.get("type").and_then(Value::as_str).unwrap_or("?");
        let key = match record
            .get("attachment")
            .and_then(|a| a.get("type"))
            .and_then(Value::as_str)
        {
            Some(sub) if kind == "attachment" => format!("attachment:{sub}"),
            _ => kind.to_string(),
        };
        *out.entry(key).or_insert(0) += 1;
    }
    out
}

/// Every session transcript under `root`, with its bucket. Subagent
/// transcripts sit one directory deeper and are not sessions of their own.
pub fn transcripts(root: &Path) -> Vec<(PathBuf, String)> {
    let mut out = Vec::new();
    let Ok(buckets) = std::fs::read_dir(root) else {
        return out;
    };
    for bucket in buckets.flatten() {
        if !bucket.file_type().map(|t| t.is_dir()).unwrap_or(false) {
            continue;
        }
        let name = bucket.file_name().to_string_lossy().to_string();
        let Ok(files) = std::fs::read_dir(bucket.path()) else {
            continue;
        };
        for file in files.flatten() {
            let path = file.path();
            if file.file_type().map(|t| t.is_file()).unwrap_or(false)
                && path.extension().and_then(|e| e.to_str()) == Some("jsonl")
            {
                out.push((path, name.clone()));
            }
        }
    }
    out
}

/// The record fields listing needs, borrowed from the line instead of decoded.
#[derive(Deserialize)]
struct LightRecord<'a> {
    #[serde(rename = "type", borrow, default)]
    kind: Option<&'a RawValue>,
    #[serde(borrow, default)]
    cwd: Option<&'a RawValue>,
    #[serde(borrow, default)]
    timestamp: Option<&'a RawValue>,
    #[serde(rename = "isMeta", default)]
    is_meta: Option<bool>,
    #[serde(rename = "isSidechain", default)]
    is_sidechain: Option<bool>,
    #[serde(rename = "isCompactSummary", default)]
    is_compact_summary: Option<bool>,
    #[serde(borrow, default)]
    message: Option<&'a RawValue>,
    #[serde(rename = "customTitle", borrow, default)]
    custom_title: Option<&'a RawValue>,
    #[serde(rename = "agentName", borrow, default)]
    agent_name: Option<&'a RawValue>,
    #[serde(rename = "aiTitle", borrow, default)]
    ai_title: Option<&'a RawValue>,
    #[serde(borrow, default)]
    summary: Option<&'a RawValue>,
}

/// The message fields listing needs.
#[derive(Deserialize)]
struct LightMessage<'a> {
    #[serde(borrow, default)]
    id: Option<&'a RawValue>,
    #[serde(borrow, default)]
    model: Option<&'a RawValue>,
    #[serde(borrow, default)]
    content: Option<&'a RawValue>,
}

/// One content block, reduced to its type and text.
#[derive(Deserialize)]
struct LightBlock<'a> {
    #[serde(rename = "type", borrow, default)]
    kind: Option<&'a RawValue>,
    #[serde(borrow, default)]
    text: Option<&'a RawValue>,
}

/// A raw JSON string's contents, borrowed unless it holds escapes.
fn raw_str(raw: &RawValue) -> Option<Cow<'_, str>> {
    let text = raw.get();
    let inner = text.strip_prefix('"')?.strip_suffix('"')?;
    if inner.contains('\\') {
        serde_json::from_str::<String>(text).ok().map(Cow::Owned)
    } else {
        Some(Cow::Borrowed(inner))
    }
}

/// Text of a user message's content when it is something a person typed: a
/// string, or text blocks without any tool output among them.
fn light_prompt(content: &RawValue) -> Option<String> {
    if let Some(text) = raw_str(content) {
        return Some(text.into_owned());
    }
    let blocks: Vec<LightBlock> = serde_json::from_str(content.get()).ok()?;
    let mut parts = Vec::new();
    for block in &blocks {
        match block.kind.and_then(raw_str).as_deref() {
            Some("tool_result") => return None,
            Some("text") => {
                if let Some(text) = block.text.and_then(raw_str) {
                    parts.push(text);
                }
            }
            _ => {}
        }
    }
    (!parts.is_empty()).then(|| parts.join("\n"))
}

/// Gathers one transcript's listing metadata in a single streaming pass.
fn inspect(path: &Path, bucket: &str, registered: &[String]) -> Option<SessionRef> {
    let metadata = std::fs::metadata(path).ok()?;
    let mtime = mtime_ms(&metadata);
    let file = File::open(path).ok()?;
    let mut reader = BufReader::with_capacity(1 << 20, file);

    let mut cwd: Option<String> = None;
    let mut started: Option<i64> = None;
    let mut names = Names::default();
    let mut first_prompt: Option<String> = None;
    let mut messages = 0usize;
    let mut replies = 0usize;
    let mut prompts: Vec<u64> = Vec::new();
    let mut last_response = String::new();

    let mut buffer = Vec::new();
    loop {
        buffer.clear();
        match reader.read_until(b'\n', &mut buffer) {
            Ok(0) | Err(_) => break,
            Ok(_) => {}
        }
        let line = String::from_utf8_lossy(&buffer);
        let Ok(record) = serde_json::from_str::<LightRecord>(&line) else {
            continue;
        };
        if cwd.is_none() {
            if let Some(found) = record.cwd.and_then(raw_str).filter(|c| !c.is_empty()) {
                cwd = Some(found.into_owned());
            }
        }
        if let Some(ms) = record.timestamp.and_then(raw_str).and_then(|t| from_iso(&t)) {
            started.get_or_insert(ms);
        }
        let Some(kind) = record.kind.and_then(raw_str) else {
            continue;
        };
        match kind.as_ref() {
            "user" | "assistant" => {
                // In a session transcript, sidechain records belong to subagents.
                if record.is_sidechain == Some(true) {
                    continue;
                }
                let Some(message) = record
                    .message
                    .and_then(|m| serde_json::from_str::<LightMessage>(m.get()).ok())
                else {
                    continue;
                };
                if kind == "assistant" {
                    // Claude Code writes one record per content block of a reply.
                    let response = message.id.map(|id| id.get()).unwrap_or_default();
                    if response.is_empty() || response != last_response {
                        messages += 1;
                        last_response = response.to_string();
                        let model = message.model.and_then(raw_str);
                        if model.as_deref() != Some(SYNTHETIC_MODEL) {
                            replies += 1;
                        }
                    }
                    continue;
                }
                last_response.clear();
                if record.is_meta == Some(true) || record.is_compact_summary == Some(true) {
                    continue;
                }
                messages += 1;
                if let Some(text) = message.content.and_then(light_prompt) {
                    if first_prompt.is_none() {
                        // Command envelopes and interruption notices are not
                        // something the user typed; the label skips them.
                        let collapsed = text.split_whitespace().collect::<Vec<_>>().join(" ");
                        if !collapsed.is_empty() && !collapsed.starts_with(['<', '[']) {
                            first_prompt = Some(collapsed);
                        }
                    }
                    if let Some(print) = dedup::fingerprint(&text) {
                        prompts.push(print);
                    }
                }
            }
            other => {
                let raw = match other {
                    "custom-title" => record.custom_title,
                    "agent-name" => record.agent_name,
                    "ai-title" => record.ai_title,
                    "summary" => record.summary,
                    _ => None,
                };
                if let Some(text) = raw.and_then(raw_str) {
                    names.observe(other, &text);
                }
            }
        }
    }
    prompts.sort_unstable();
    prompts.dedup();

    Some(SessionRef {
        id: session_id(path),
        path: path.to_path_buf(),
        bucket: bucket.to_string(),
        cwd: cwd.unwrap_or_else(|| bucket_cwd(bucket, registered)),
        started: started.unwrap_or(mtime),
        name: names.best(),
        first_prompt: first_prompt.unwrap_or_default(),
        messages,
        replies,
        prompts,
        subagents: subagent_files(path).len(),
        size: metadata.len(),
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn a_user_rename_outranks_a_later_generated_title() {
        let mut names = Names::default();
        names.observe("ai-title", "Generated");
        names.observe("custom-title", "Mine");
        names.observe("ai-title", "Generated again");
        let best = names.best().unwrap();
        assert_eq!(best.text, "Mine");
        assert_eq!(best.source.title_source(), "user");
    }

    #[test]
    fn the_latest_record_of_a_kind_wins() {
        let mut names = Names::default();
        names.observe("ai-title", "First");
        names.observe("ai-title", "Second");
        names.observe("custom-title", "   ");
        let best = names.best().unwrap();
        assert_eq!(best.text, "Second");
        assert_eq!(best.source, NameSource::Ai);
    }

    #[test]
    fn origin_takes_the_first_cwd_and_timestamp_in_file_order() {
        let records = vec![
            json!({"type": "last-prompt", "lastPrompt": "x"}),
            json!({"type": "user", "timestamp": "2026-09-01T10:00:00.000Z"}),
            json!({"type": "user", "cwd": "/w", "timestamp": "2026-09-01T11:00:00.000Z"}),
            json!({"type": "user", "cwd": "/other"}),
        ];
        let origin = Origin::of(&records);
        assert_eq!(origin.cwd.as_deref(), Some("/w"));
        assert_eq!(origin.started, from_iso("2026-09-01T10:00:00.000Z"));
    }

    #[test]
    fn tool_output_is_not_a_prompt() {
        let typed = RawValue::from_string(r#"[{"type":"text","text":"a"},{"type":"text","text":"b"}]"#.into()).unwrap();
        assert_eq!(light_prompt(&typed).as_deref(), Some("a\nb"));
        let tool = RawValue::from_string(r#"[{"type":"tool_result","tool_use_id":"t","content":"x"}]"#.into()).unwrap();
        assert_eq!(light_prompt(&tool), None);
        let plain = RawValue::from_string(r#""say \"hi\"""#.into()).unwrap();
        assert_eq!(light_prompt(&plain).as_deref(), Some("say \"hi\""));
    }

    #[test]
    fn an_unregistered_bucket_falls_back_to_the_naive_reading() {
        let registered = vec!["/Users/me.x/app".to_string()];
        assert_eq!(bucket_cwd("-Users-me-x-app", &registered), "/Users/me.x/app");
        assert_eq!(bucket_cwd("-opt-app", &registered), "/opt/app");
    }
}
